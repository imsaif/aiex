import Anthropic from '@anthropic-ai/sdk';
import { JudgeScoresSchema, type JudgeScores } from './types';

const JUDGE_MODEL = 'claude-sonnet-4-20250514';

function buildJudgePrompt(opts: {
  fixtureDescription: string;
  fixtureNotes: string;
  productType: string;
  auditJson: string;
}): string {
  return `You are an evaluator scoring the quality of an AI UX audit. The audit was generated by another AI given a single screenshot. You see the same screenshot AND the audit's JSON output. Your job is to score the audit honestly across 5 axes.

## Surface under review
- Product type: ${opts.productType}
- Fixture description: ${opts.fixtureDescription}
- Curator notes: ${opts.fixtureNotes || '(none)'}

## Audit output (JSON)
\`\`\`json
${opts.auditJson}
\`\`\`

## Scoring rubric (each axis 0–5)

1. **faithfulness** — Does each finding's \`evidence\` field quote or describe text/elements ACTUALLY present in the screenshot? Penalize made-up UI elements. 5 = every finding's evidence is verifiable in the image; 0 = findings reference elements that don't exist.
2. **specificity** — Does each \`finding\` reference concrete UI ("the input box at bottom has no token counter") rather than generic pattern descriptions ("the chat lacks confidence visualization")? 5 = every finding is anchored on visible UI; 0 = pattern restatements with no surface grounding.
3. **patternFit** — Are the patterns in \`applicablePatterns\` and \`topGaps\` actually relevant to the surface shown? Penalize agentic patterns flagged on chat surfaces, error-recovery flagged on settings pages, etc. 5 = every pattern fits the surface; 0 = clearly wrong patterns dominate.
4. **actionability** — Is each \`recommendation\` a concrete fix a designer can act on this week, or is it a generic restatement of the pattern? 5 = every recommendation is specific and shippable; 0 = recommendations are pattern definitions.
5. **noFabrication** — Are there any findings, evidence quotes, or UI elements that are simply not in the screenshot? This is the most important axis. Penalize hard: even one fabricated finding drops this to 2 or below.

## Output

Return STRICT JSON only, no fences, no preamble:

{
  "faithfulness": <0-5 integer or one-decimal float>,
  "specificity": <0-5>,
  "patternFit": <0-5>,
  "actionability": <0-5>,
  "noFabrication": <0-5>,
  "comments": "1-3 sentences explaining the lowest score(s). Cite specific findings by index."
}`;
}

export async function judgeAudit(opts: {
  client: Anthropic;
  imageBase64: string;
  mediaType: 'image/png' | 'image/jpeg' | 'image/webp' | 'image/gif';
  fixtureDescription: string;
  fixtureNotes: string;
  productType: string;
  auditJson: unknown;
}): Promise<{ ok: true; scores: JudgeScores } | { ok: false; error: string }> {
  const prompt = buildJudgePrompt({
    fixtureDescription: opts.fixtureDescription,
    fixtureNotes: opts.fixtureNotes,
    productType: opts.productType,
    auditJson: JSON.stringify(opts.auditJson, null, 2),
  });

  let response;
  try {
    response = await opts.client.messages.create({
      model: JUDGE_MODEL,
      max_tokens: 1024,
      messages: [
        {
          role: 'user',
          content: [
            {
              type: 'image',
              source: { type: 'base64', media_type: opts.mediaType, data: opts.imageBase64 },
            },
            { type: 'text', text: prompt },
          ],
        },
      ],
    });
  } catch (err) {
    return { ok: false, error: err instanceof Error ? err.message : 'judge call threw' };
  }

  const textBlock = response.content.find((b) => b.type === 'text');
  if (!textBlock || textBlock.type !== 'text') {
    return { ok: false, error: 'judge returned no text block' };
  }

  // Reuse the same brace-balanced extraction style as the production parser.
  const match = textBlock.text.match(/\{[\s\S]*\}/);
  if (!match) return { ok: false, error: 'judge returned no JSON' };

  let parsed: unknown;
  try {
    parsed = JSON.parse(match[0]);
  } catch (err) {
    return { ok: false, error: `judge JSON.parse failed: ${err instanceof Error ? err.message : 'unknown'}` };
  }

  const validation = JudgeScoresSchema.safeParse(parsed);
  if (!validation.success) {
    return {
      ok: false,
      error: `judge schema mismatch: ${validation.error.issues
        .slice(0, 3)
        .map((i) => `${i.path.join('.')}: ${i.message}`)
        .join('; ')}`,
    };
  }

  return { ok: true, scores: validation.data };
}
